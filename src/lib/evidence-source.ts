// 证据**来源分级**（张楚寒 2026-07-30 第二轮）。相对导入、无 IO、可测。
//
// 原话：「建议建立统一等级：
//   1. 财报、交易所公告、监管文件
//   2. 公司电话会、管理层正式披露
//   3. 行业销量、价格、招投标、订单数据
//   4. 权威媒体报道
//   5. 券商研报
//   6. 市场传闻、社交媒体
// 『已验证』最好至少需要一条能够直接支持命题的一级至三级证据。
// 只有研报观点或者AI推断，最多标为『部分验证』。」
//
// 这一级和 `evidence.ts` 里的 `grade`（direct/supporting）是**两条正交的轴**：
//   - 来源等级 = 这条信息**有多硬**（谁说的）
//   - grade    = 这条事实**是不是关于这家公司的**（说的是谁）
// 「已验证」要同时满足两条：一级到三级 **且** 直接支持命题。缺一条都只能是「部分验证」。

export type SourceLevel = 1 | 2 | 3 | 4 | 5 | 6;

export const SOURCE_LEVEL_LABEL: Record<SourceLevel, string> = {
  1: "财报 / 交易所公告 / 监管文件",
  2: "公司电话会 / 管理层正式披露",
  3: "行业数据（销量·价格·招投标·订单）",
  4: "权威媒体报道",
  5: "券商研报",
  6: "市场传闻 / 社交媒体",
};

/** 追踪器一行里放得下的短标签。 */
export const SOURCE_LEVEL_SHORT: Record<SourceLevel, string> = {
  1: "一级·公告",
  2: "二级·管理层",
  3: "三级·行业数据",
  4: "四级·媒体",
  5: "五级·研报",
  6: "六级·传闻",
};

/** 一级到三级＝可以支撑「已验证」的硬证据。 */
export const HARD_SOURCE_MAX: SourceLevel = 3;

export function isHardSource(level: SourceLevel): boolean {
  return level <= HARD_SOURCE_MAX;
}

