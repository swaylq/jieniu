// 判据。词表按**真库里实际存在的来源名**写（近 7 天全量分布），不照想象编。
// ---------------------------------------------------------------------------

/** ① 财报 / 交易所公告 / 监管文件。含交易所自己披露的结构化数据（龙虎榜、大宗交易、增减持）。 */
const L1_SOURCE =
  /公告|巨潮|业绩预告|业绩快报|龙虎榜|大宗交易|股东增减持|董监高增减持|交易所|证监会|证券交易所|监管/;
const L1_TITLE =
  /年度报告|半年度?报告|季度报告|年报|半年报|季报|中报|业绩(预告|快报|预增|预减|预亏|扭亏)|招股(说明书|意向书)|问询函|关注函|监管(函|措施|意见)|立案|处罚决定|上市公告书|权益变动报告书|要约收购/;

/** ② 公司电话会 / 管理层正式披露。 */
const L2 =
  /投资者关系活动记录表|业绩说明会|电话会(议)?|路演|机构调研纪要|调研纪要|互动易|e互动|投资者互动|董事长(表示|称|回应)|管理层(表示|称|回应|指出)|公司(回应|表示|澄清|说明)/;

/** ③ 行业销量 / 价格 / 招投标 / 订单数据。 */
const L3_SOURCE =
  /统计局|海关|工信部|乘联会|中汽协|半导体行业协会|光伏行业协会|钢铁工业协会|SEMI|TrendForce|集邦|IDC|Counterpoint|Canalys|Omdia|Wind|同花顺iFinD|中国电子|行业协会/;
const L3_TITLE =
  /销量|产量|出货量|装机量|价格指数|现货价|均价|报价(上调|下调)|价格.{0,4}(环比|同比)|(环比|同比).{0,6}价格|涨价|降价|提价|调价|招标|中标|投标|订单|在手订单|开工率|产能利用率|库存(周转|水平|天数)?|排产|稼动率|渗透率|市占率|市场份额数据/;

/** ⑤ 券商研报。 */
const L5 =
  /研报|研究报告|券商|分析师|评级|首次覆盖|目标价|维持.{0,6}(买入|增持|推荐|持有|中性)|上调评级|下调评级|盈利预测/;

/** ⑥ 市场传闻 / 社交媒体。**没有编辑问责**的那一档。 */
const L6 =
  /传闻|据传|市场传言|网传|坊间|小道消息|知情人士(透露|称)|据悉|有消息称|股吧|雪球|微博|抖音|自媒体|论坛/;

/** 权威媒体：有编辑问责的正规媒体。 */
const AUTHORITATIVE_MEDIA =
  /新华|人民日报|央视|中央广播电视总台|经济日报|证券时报|上海证券报|上证报|中国证券报|中证|证券日报|财联社|第一财经|华尔街见闻|21世纪经济报道|界面|每日经济新闻|中新经纬|财新|澎湃|证券市场周刊|金融时报|中国基金报/;

/**
 * 聚合站会把真正的出处写在摘要开头的方括号里（「【每日经济新闻】…」「【财联社】…」）。
 * 真库里 5192 条「东方财富·个股资讯」几乎全是转载，只看 source 名字会把它们一律当成
 * 同一个来源，分不出「新华社的稿」和「某公众号的稿」。
 */
export function originFromBrief(brief: string): string | null {
  const m = /^\s*[【[]([^】\]]{2,20})[】\]]/.exec(brief);
  return m?.[1] ?? null;
}

export type SourceInput = {
  /** 库里的来源名，如「东方财富·公告」。 */
  sourceName: string;
  /** PRIMARY = 一手（公司公告 / 交易所）。 */
  tier: string;
  title: string;
  brief?: string;
};

/**
 * 一条资讯落在六级里的哪一级。
 *
 * 判定顺序是**从硬到软**，但传闻优先——一条「据传公司将扩产」哪怕挂在权威媒体下面，
 * 也还是传闻，不能因为转载它的人体面就升一级。
 */
export function classifySourceLevel(i: SourceInput): SourceLevel {
  const t = i.title;
  const brief = i.brief ?? "";
  const origin = originFromBrief(brief) ?? "";
  const src = i.sourceName;

  // 传闻/社交先判：措辞比载体更能说明这条信息有多硬
  if (L6.test(t) || L6.test(brief)) return 6;

  // ② 管理层正式披露。**排在 ① 前面**：「投资者关系活动记录表」「业绩说明会」是以公告形式
  // 披露的（source 就是「东方财富·公告」、tier=PRIMARY），但内容是管理层口径而不是审计过的
  // 财务数据——按张楚寒的分级，它属于第二级。先判 ① 会把整类都提到一级。
  if (L2.test(t) || L2.test(brief)) return 2;

  // ① 一手披露
  if (i.tier === "PRIMARY" && L1_SOURCE.test(src)) return 1;
  if (L1_TITLE.test(t)) return 1;
  if (L1_SOURCE.test(src) && !src.includes("研报")) return 1;

  // ③ 行业数据（第三方数据机构，或标题里就是量价/招投标/订单本身）
  if (L3_SOURCE.test(src) || L3_SOURCE.test(origin) || L3_TITLE.test(t)) return 3;

  // ⑤ 研报（排在 ④ 前面：研报常由权威媒体转载，但它仍然是观点不是事实）
  if (L5.test(t) || L5.test(src)) return 5;

  // ④ 权威媒体
  if (AUTHORITATIVE_MEDIA.test(src) || AUTHORITATIVE_MEDIA.test(origin)) return 4;

  /**
   * 兜底给 4 而不是 6：六级那一档是留给**没有编辑问责**的内容（传闻、社交、自媒体）。
   * 「东方财富·快讯」「东方财富·个股资讯」这类聚合站是有编辑的正规渠道，只是认不出原始出处，
   * 把它们打成「传闻」会让绝大多数证据凭空掉两级——那是判据在撒谎，不是在保守。
   */
  return 4;
}
